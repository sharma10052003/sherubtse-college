export type DepartmentsLabelFn = (key: string) => string;

export function makeDepartmentsLabels(custom?: Record<string, string> | null): DepartmentsLabelFn {
  return (key) => {
    const v = custom?.[key];
    return typeof v === 'string' && v.trim() ? v.trim() : (DEPARTMENTS_LABEL_DEFAULTS[key] ?? '');
  };
}
